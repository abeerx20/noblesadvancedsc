const originalText = new WeakMap();
const originalElements = new WeakMap();
const reverseTranslations = Object.fromEntries(Object.entries(translations).map(([arabic, english]) => [english, arabic]));
const normalizedTranslations = Object.fromEntries(Object.entries(translations).map(([arabic, english]) => [arabic.replace(/\s+/g, " ").trim(), english]));
const normalizedReverseTranslations = Object.fromEntries(Object.entries(normalizedTranslations).map(([arabic, english]) => [english, arabic]));

function translateValue(value, toEnglish) {
    const normalized = value.replace(/\s+/g, " ").trim();
    return toEnglish ? normalizedTranslations[normalized] ?? value : normalizedReverseTranslations[normalized] ?? reverseTranslations[value] ?? value;
}

function translateTextNodes(toEnglish) {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
        if (node.parentElement && originalElements.has(node.parentElement)) return;
        if (!originalText.has(node)) originalText.set(node, node.nodeValue);
        const source = originalText.get(node);
        const trimmed = source.trim();
        if (!trimmed) return;
        node.nodeValue = source.replace(trimmed, translateValue(trimmed, toEnglish));
    });
}

function translateLeafElements(toEnglish) {
    document.querySelectorAll("body *:not(script):not(style)").forEach((element) => {
        if (element.children.length) return;
        if (!originalElements.has(element)) originalElements.set(element, element.textContent);
        const source = originalElements.get(element);
        const translated = translateValue(source, toEnglish);
        if (translated !== source || normalizedTranslations[source.replace(/\s+/g, " ").trim()]) element.textContent = translated;
    });
}

function translateAttributes(toEnglish) {
    document.querySelectorAll("[alt], [aria-label], [title], [placeholder]").forEach((element) => {
        ["alt", "aria-label", "title", "placeholder"].forEach((attribute) => {
            if (!element.hasAttribute(attribute)) return;
            const key = `${attribute}Original`;
            if (!element.dataset[key]) element.dataset[key] = element.getAttribute(attribute);
            element.setAttribute(attribute, translateValue(element.dataset[key], toEnglish));
        });
    });
}

function setLanguage(language) {
    const toEnglish = language === "en";
    document.documentElement.lang = toEnglish ? "en" : "ar";
    document.documentElement.dir = toEnglish ? "ltr" : "rtl";
    document.body.classList.toggle("language-english", toEnglish);
    translateLeafElements(toEnglish);
    translateTextNodes(toEnglish);
    translateAttributes(toEnglish);
    const languageLink = document.querySelector(".language-toggle");
    if (languageLink) languageLink.textContent = toEnglish ? "العربية" : "English";
    document.title = toEnglish ? "Advanced Al-Nubala Schools" : "مدارس النبلاء المتقدمة";
    localStorage.setItem("nas-language", language);
}

function initLanguageToggle() {
    const languageLink = [...document.querySelectorAll("a, button")].find((element) => element.textContent.trim() === "English" || element.textContent.trim() === "العربية");
    if (!languageLink) return;
    languageLink.classList.add("language-toggle");
    languageLink.href = "#";
    languageLink.addEventListener("click", (event) => {
        event.preventDefault();
        setLanguage(document.documentElement.lang === "en" ? "ar" : "en");
    });
    setLanguage(localStorage.getItem("nas-language") === "en" ? "en" : "ar");
}

document.addEventListener("DOMContentLoaded", initLanguageToggle);
